func (g *webGenerator) contractValidationTests() string {
	var builder strings.Builder
	for _, entity := range g.entitiesWithGeneratedValidation() {
		validName := "valid" + entity.Name + "Input"
		builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = %s;\n", validName, g.contractEntityInputLiteral(entity)))
		builder.WriteString(fmt.Sprintf("assertValid(validate%sInput(%s), %q);\n", entity.Name, validName, entity.Name+" valid input"))
		for _, field := range entity.Fields {
			inputName := g.contractInputFieldName(entity, field)
			if hasModifier(field, "required") && modifierValue(field, "default") == "" {
				missingName := lowerCamelCase(entity.Name) + "Missing" + title(field.Name)
				builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = { ...%s };\n", missingName, validName))
				builder.WriteString(fmt.Sprintf("delete %s[%q];\n", missingName, inputName))
				builder.WriteString(fmt.Sprintf("assertInvalid(validate%sInput(%s), %q);\n", entity.Name, missingName, entity.Name+" missing "+inputName))
			}
			if field.Type == "number" || field.Type == "integer" {
				fractionalName := lowerCamelCase(entity.Name) + "Fractional" + title(field.Name)
				builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = { ...%s, %s: 1.5 };\n", fractionalName, validName, inputName))
				builder.WriteString(fmt.Sprintf("assertInvalid(validate%sInput(%s), %q);\n", entity.Name, fractionalName, entity.Name+" fractional "+inputName))
			}
		}
		for _, action := range customActionsForEntity(g.program, entity.Name) {
			validAction := "valid" + action.Name + "Input"
			builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = %s;\n", validAction, contractActionInputLiteral(action)))
			builder.WriteString(fmt.Sprintf("assertValid(validate%sInput(%s), %q);\n", action.Name, validAction, action.Name+" valid input"))
			for _, input := range action.Inputs {
				if hasModifier(input, "required") && modifierValue(input, "default") == "" {
					missingName := lowerCamelCase(action.Name) + "Missing" + title(input.Name)
					builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = { ...%s };\n", missingName, validAction))
					builder.WriteString(fmt.Sprintf("delete %s[%q];\n", missingName, input.Name))
					builder.WriteString(fmt.Sprintf("assertInvalid(validate%sInput(%s), %q);\n", action.Name, missingName, action.Name+" missing "+input.Name))
				}
				if input.Type == "number" || input.Type == "integer" {
					fractionalName := lowerCamelCase(action.Name) + "Fractional" + title(input.Name)
					builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = { ...%s, %s: 1.5 };\n", fractionalName, validAction, input.Name))
					builder.WriteString(fmt.Sprintf("assertInvalid(validate%sInput(%s), %q);\n", action.Name, fractionalName, action.Name+" fractional "+input.Name))
				}
				if minValue := modifierValue(input, "min"); minValue != "" && (input.Type == "number" || input.Type == "integer" || input.Type == "decimal" || input.Type == "money") {
					if invalid, ok := contractBelowMinLiteral(minValue); ok {
						minName := lowerCamelCase(action.Name) + "BelowMin" + title(input.Name)
						builder.WriteString(fmt.Sprintf("const %s: Record<string, unknown> = { ...%s, %s: %s };\n", minName, validAction, input.Name, invalid))
						builder.WriteString(fmt.Sprintf("assertInvalid(validate%sInput(%s), %q);\n", action.Name, minName, action.Name+" below min "+input.Name))
					}
				}
			}
		}
		builder.WriteString("\n")
	}
	return builder.String()
}

func (g *webGenerator) contractEntityInputLiteral(entity EntityDecl) string {
	parts := []string{}
	for _, field := range entity.Fields {
		inputName := g.contractInputFieldName(entity, field)
		parts = append(parts, fmt.Sprintf("%s: %s", inputName, contractFieldValueLiteral(field)))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func (g *webGenerator) contractInputFieldName(entity EntityDecl, field FieldDecl) string {
	if g.isRelationField(field) {
		return relationIDFieldName(field)
	}
	return field.Name
}

func contractActionInputLiteral(action CustomActionDecl) string {
	parts := []string{}
	for _, input := range action.Inputs {
		parts = append(parts, fmt.Sprintf("%s: %s", input.Name, contractFieldValueLiteral(input)))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func contractFieldValueLiteral(field FieldDecl) string {
	switch field.Type {
	case "email":
		return contractJSONString(contractStringValue(field, "agent@example.com"))
	case "number", "integer":
		return contractIntegerValue(field)
	case "decimal", "money":
		return contractDecimalValue(field)
	case "boolean":
		return "true"
	case "date":
		return `"2026-09-06"`
	case "datetime":
		return `"2026-09-06T12:00:00Z"`
	case "file":
		return `"data:application/octet-stream;base64,AA=="`
	case "image":
		return `"data:image/png;base64,AA=="`
	default:
		if hasModifier(field, "url") {
			return contractJSONString(contractStringValue(field, "https://example.com"))
		}
		return contractJSONString(contractStringValue(field, "Sample"))
	}
}

func contractStringValue(field FieldDecl, fallback string) string {
	value := fallback
	if pattern := modifierValue(field, "regex"); pattern != "" {
		if strings.Contains(pattern, "A-Z") || strings.Contains(pattern, "\\d") || strings.Contains(pattern, "0-9") {
			value = "ABC123"
		}
	}
	if minLength, maxLength, ok := fieldLengthBounds(field); ok {
		target := minLength
		if target < 1 {
			target = 1
		}
		if target > maxLength {
			target = maxLength
		}
		if target > 0 {
			value = strings.Repeat("A", target)
		}
	}
	return value
}

func contractIntegerValue(field FieldDecl) string {
	value := 1.0
	if minValue, ok := contractNumericModifier(field, "min"); ok && value < minValue {
		value = math.Ceil(minValue)
	}
	if maxValue, ok := contractNumericModifier(field, "max"); ok && value > maxValue {
		value = math.Floor(maxValue)
	}
	return strconv.FormatInt(int64(value), 10)
}

func contractDecimalValue(field FieldDecl) string {
	value := 1.25
	if minValue, ok := contractNumericModifier(field, "min"); ok && value < minValue {
		value = minValue
	}
	if maxValue, ok := contractNumericModifier(field, "max"); ok && value > maxValue {
		value = maxValue
	}
	return strconv.FormatFloat(value, 'f', -1, 64)
}

func contractNumericModifier(field FieldDecl, name string) (float64, bool) {
	value := modifierValue(field, name)
	if value == "" {
		return 0, false
	}
	parsed, err := strconv.ParseFloat(value, 64)
	return parsed, err == nil && !math.IsInf(parsed, 0) && !math.IsNaN(parsed)
}

func contractBelowMinLiteral(value string) (string, bool) {
	parsed, err := strconv.ParseFloat(value, 64)
	if err != nil || math.IsInf(parsed, 0) || math.IsNaN(parsed) {
		return "", false
	}
	return strconv.FormatFloat(parsed-1, 'f', -1, 64), true
}

func contractJSONString(value string) string {
	encoded, _ := json.Marshal(value)
	return string(encoded)
}
