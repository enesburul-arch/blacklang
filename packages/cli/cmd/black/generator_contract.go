func (g *webGenerator) entitiesWithGeneratedValidation() []EntityDecl {
	sources := map[string]bool{}
	for _, page := range g.program.Pages {
		sources[page.Source] = true
	}
	entities := []EntityDecl{}
	for _, entity := range g.program.Entities {
		if sources[entity.Name] {
			entities = append(entities, entity)
		}
	}
	return entities
}

